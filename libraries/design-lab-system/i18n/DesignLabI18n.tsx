const dictionaries: Record<string, Messages> = { en: en as Messages, ru }
const I18nContext = createContext({
  locale: 'en' as Locale,
  t: (key: MessageKey) => en[key] as string,
})

export function DesignLabI18nProvider({
  locale = 'en',
  messages,
  children,
}: {
  locale?: Locale
  messages?: Partial<Messages>
  children: ReactNode
}) {
  const value = useMemo(() => {
    const dictionary = { ...en, ...(dictionaries[locale] ?? {}), ...messages } as Messages
    return { locale, t: (key: MessageKey) => dictionary[key] ?? en[key] }
  }, [locale, messages])
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useDesignLabI18n() {
  return useContext(I18nContext)
}
